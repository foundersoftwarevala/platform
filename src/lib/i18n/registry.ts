/* ------------------------------------------------------------------ lookup */

const BY_CODE = new Map<string, LanguageDefinition>();
const BY_ALIAS = new Map<string, LanguageDefinition>();
const BY_ISO3 = new Map<string, LanguageDefinition>();
const BY_NAME = new Map<string, LanguageDefinition>();
const BY_LEGACY = new Map<string, LanguageDefinition>();

for (const language of LANGUAGE_REGISTRY) {
  BY_CODE.set(language.code.toLowerCase(), language);
  for (const alias of language.aliases) BY_ALIAS.set(alias.toLowerCase(), language);
  if (!language.region && !language.replacedBy && !BY_ISO3.has(language.iso639_3)) {
    BY_ISO3.set(language.iso639_3, language);
  }
  for (const name of [language.name, language.nativeName]) {
    const key = name.toLowerCase();
    if (!BY_NAME.has(key)) BY_NAME.set(key, language);
  }
  if (language.legacyCode) BY_LEGACY.set(language.legacyCode, language);
}

/**
 * Legacy codes accepted without being asked to. These are the old identifiers
 * that are not also real language codes, so reading them cannot turn a request
 * for one language into another. "AM" (old: Armenian, ISO: Amharic), "BR" (old:
 * Brazilian Portuguese, ISO: Breton) and "CO" (old: Colombian Spanish, ISO:
 * Corsican) are deliberately excluded: as bare input they mean the ISO
 * language, and only an explicit legacy read maps them the old way.
 */
const IMPLICIT_LEGACY = new Set(["MX", "CL", "PE", "ZT", "YU"]);

function isImplicitLegacyCode(code: string): boolean {
  return /\d/.test(code) || IMPLICIT_LEGACY.has(code);
}

const LANGUAGE_SUBTAG = /^[a-z]{2,3}$/;
const SCRIPT_SUBTAG = /^[a-z]{4}$/;
const REGION_SUBTAG = /^(?:[a-z]{2}|\d{3})$/;

export type ResolveOptions = {
  /**
   * Treat the input as a value written by the previous catalogue, so "AM" is
   * Armenian rather than Amharic. Only for reading old stored values.
   */
  legacy?: boolean;
  /** Also match English and native language names ("Hindi", "हिन्दी"). */
  names?: boolean;
  /** Return disabled languages too. Off by default. */
  includeDisabled?: boolean;
};

function lookupTag(tag: string): LanguageDefinition | undefined {
  return BY_CODE.get(tag) ?? BY_ALIAS.get(tag);
}

function resolveAny(input: string | null | undefined, options: ResolveOptions) {
  if (typeof input !== "string") return undefined;
  const raw = input.trim();
  if (!raw || raw.length > 64) return undefined;

  if (options.legacy) {
    const legacy = BY_LEGACY.get(raw.toUpperCase());
    if (legacy) return legacy;
  }

  const tag = raw.replace(/_/g, "-").toLowerCase();
  const direct = lookupTag(tag);
  if (direct) return direct;

  const [lang, ...rest] = tag.split("-");
  if (lang && LANGUAGE_SUBTAG.test(lang)) {
    const script = rest.find((part) => SCRIPT_SUBTAG.test(part));
    const region = rest.find((part) => REGION_SUBTAG.test(part));
    const candidates = [
      script && region ? `${lang}-${script}-${region}` : null,
      region ? `${lang}-${region}` : null,
      script ? `${lang}-${script}` : null,
      lang,
    ];
    for (const candidate of candidates) {
      if (!candidate) continue;
      const hit = lookupTag(candidate);
      if (hit) return hit;
    }
    if (lang.length === 3 && rest.length === 0) {
      const iso3 = BY_ISO3.get(lang);
      if (iso3) return iso3;
    }
  }

  const upper = raw.toUpperCase();
  if (isImplicitLegacyCode(upper)) {
    const legacy = BY_LEGACY.get(upper);
    if (legacy) return legacy;
  }

  if (options.names) {
    const named = BY_NAME.get(raw.toLowerCase());
    if (named) return named;
  }
  return undefined;
}

/**
 * Turn any reasonable way of naming a language into its registry entry.
 *
 * Accepts canonical codes in any case ("HI", "pt-br"), BCP 47 tags with extra
 * subtags ("zh-Hant-HK", "en_US"), well-known aliases ("iw", "tl", "zh-TW"),
 * ISO 639-3 codes ("hin"), and, when asked, language names and legacy codes.
 * Returns undefined for anything else. It never guesses.
 */
export function resolveLanguage(
  input: string | null | undefined,
  options: ResolveOptions = {},
): LanguageDefinition | undefined {
  const found = resolveAny(input, options);
  if (!found) return undefined;
  if (options.includeDisabled) return found;
  // A retired language resolves to the language that replaced it.
  if (found.replacedBy) return BY_CODE.get(found.replacedBy.toLowerCase());
  return found.enabled ? found : undefined;
}

/** The canonical code for an input, or null when it is not a supported language. */
export function normalizeLanguageCode(
  input: string | null | undefined,
  options?: ResolveOptions,
): string | null {
  return resolveLanguage(input, options)?.code ?? null;
}

export function isSupportedLanguage(input: string | null | undefined, options?: ResolveOptions) {
  return resolveLanguage(input, options) !== undefined;
}

/** The registry entry for a code already known to be canonical. */
export function getLanguage(code: string): LanguageDefinition | undefined {
  return BY_CODE.get(code.toLowerCase());
}

export function getSourceLanguage(): LanguageDefinition {
  return BY_CODE.get(SOURCE_LANGUAGE)!;
}

export function getDirection(code: string): TextDirection {
  return resolveLanguage(code, { includeDisabled: true })?.direction ?? "ltr";
}

export function isRtl(code: string): boolean {
  return getDirection(code) === "rtl";
}

/**
 * The languages to try for a string, most specific first: the language itself,
 * its configured fallbacks, and the source language last. "pt-BR" gives
 * ["pt-BR", "pt", "en"]; "yue" gives ["yue", "zh-Hant", "en"].
 */
export function getFallbackChain(code: string): string[] {
  const start = resolveLanguage(code, { includeDisabled: true });
  if (!start) return [SOURCE_LANGUAGE];
  const chain: string[] = [];
  const visit = (language: LanguageDefinition | undefined) => {
    if (!language || chain.includes(language.code)) return;
    chain.push(language.code);
    for (const next of language.fallback) visit(getLanguage(next));
  };
  visit(start);
  if (!chain.includes(SOURCE_LANGUAGE)) chain.push(SOURCE_LANGUAGE);
  return chain;
}

export function listLanguages(options: { includeDisabled?: boolean } = {}): LanguageDefinition[] {
  return LANGUAGE_REGISTRY.filter((language) => options.includeDisabled || language.enabled);
}

/** The active languages, in registry order. */
export const SUPPORTED_LANGUAGES: readonly LanguageDefinition[] = Object.freeze(
  LANGUAGE_REGISTRY.filter((language) => language.enabled),
);

/** A short prompt-safe description, e.g. "Spanish (Argentina) [es-AR], Latn script". */
export function describeLanguage(language: LanguageDefinition): string {
  const parts = [`${language.name} [${language.code}]`, `${language.script} script`];
  if (language.region) parts.push(`region ${language.region}`);
  if (language.direction === "rtl") parts.push("right-to-left");
  return parts.join(", ");
}
