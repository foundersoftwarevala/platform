/**
 * The language registry.
 *
 * This is the one list of languages the platform supports: exactly 140 active
 * languages. Every language code that reaches the UI, the translation service,
 * translation memory or the database is resolved against it first; anything
 * it does not know is refused.
 *
 * `code` is the canonical identifier used everywhere in the application. It is
 * a valid BCP 47 tag: a bare language subtag where one variety is meant ("hi",
 * "fr"), a script subtag where the script is what matters ("zh-Hans",
 * "zh-Hant") and a region subtag for regional variants ("pt-BR", "es-AR").
 * Script and direction agree with CLDR likely-subtags for every entry.
 *
 * Every active language is served by the platform's own translation engine
 * (services/translation-engine). Two languages of the original catalogue could
 * not be: Cantonese and Ndonga have no local model. They are kept as retired
 * entries so values stored for them still resolve, to `replacedBy`, and their
 * places were taken by Javanese and Oromo.
 *
 * The same rows are seeded into public.i18n_languages by
 * supabase/migrations/20260919000000_i18n_language_foundation.sql. Both were
 * generated from one table and a test compares them.
 *
 * `legacyCode` is the identifier the previous catalogue used. Those codes were
 * not language tags ("AM" meant Armenian, which is "hy"; "AR5" meant Spanish in
 * Argentina) and are accepted only to read values browsers already stored.
 */

export const REGISTRY_VERSION = "2026.09.2";

export const SOURCE_LANGUAGE = "en";

/** How many active languages the platform supports. */
export const SUPPORTED_LANGUAGE_COUNT = 140;

export type TextDirection = "ltr" | "rtl";

/**
 * How the interface text for a language is produced.
 * - source: the language the interface is written in
 * - partial: a reviewed UI dictionary covers part of the interface; the rest
 *   comes from translation memory and the platform's translation engine
 * - machine: text comes from translation memory and the translation engine
 * - retired: no longer offered; requests resolve to `replacedBy`
 */
export type TranslationStatus = "source" | "partial" | "machine" | "retired";

export type LanguageDefinition = {
  /** Canonical BCP 47 tag used throughout the application. */
  code: string;
  /** ISO 639-1 code, where the language has one. */
  iso639_1: string | null;
  /** ISO 639-3 (or 639-2/T macrolanguage) code. */
  iso639_3: string;
  /** The language's own full locale (speech, <html lang> consumers, hreflang). */
  locale: string;
  /**
   * Locale used for Intl number and date formatting. Differs from `locale`
   * only where CLDR has no formatting data for the language (e.g. Samoan uses
   * en-WS, Guarani es-PY).
   */
  formatLocale: string;
  /**
   * Locale whose CLDR plural rules apply, or null for languages that do not
   * inflect nouns for count (every count uses the "other" form).
   */
  pluralLocale: string | null;
  name: string;
  nativeName: string;
  /** ISO 15924 script code. */
  script: string;
  direction: TextDirection;
  /** ISO 3166-1 region, only for regional variants. */
  region: string | null;
  flag: string;
  /** False for retired languages (and any an operator switches off). */
  enabled: boolean;
  translationStatus: TranslationStatus;
  /** Languages tried, in order, when this one has no text for a string. */
  fallback: readonly string[];
  /** Other tags and spellings that mean this language (lowercase). */
  aliases: readonly string[];
  /** Identifier used by the previous catalogue, if this language was in it. */
  legacyCode: string | null;
  /** For a retired language, the language requests resolve to instead. */
  replacedBy: string | null;
};

/** Languages with a reviewed UI dictionary in src/lib/i18n/ui-dictionary.ts. */
export const DICTIONARY_LANGUAGES: readonly string[] = [
  "en",
  "hi",
  "es",
  "fr",
  "de",
  "ar",
  "zh-Hans",
  "ko",
  "ja",
  "pt",
  "bn",
  "ur",
];

const DICTIONARY_SET = new Set(DICTIONARY_LANGUAGES);

function L(
  code: string,
  iso639_1: string | null,
  iso639_3: string,
  locale: string,
  formatLocale: string,
  pluralLocale: string | null,
  name: string,
  nativeName: string,
  script: string,
  direction: TextDirection,
  region: string | null,
  flag: string,
  legacyCode: string | null,
  fallback: string[],
  aliases: string[],
  replacedBy: string | null,
): LanguageDefinition {
  const retired = replacedBy !== null;
  return Object.freeze({
    code,
    iso639_1,
    iso639_3,
    locale,
    formatLocale,
    pluralLocale,
    name,
    nativeName,
    script,
    direction,
    region,
    flag,
    enabled: !retired,
    translationStatus: retired
      ? "retired"
      : code === SOURCE_LANGUAGE
        ? "source"
        : DICTIONARY_SET.has(code)
          ? "partial"
          : "machine",
    fallback: Object.freeze(fallback),
    aliases: Object.freeze(aliases),
    legacyCode,
    replacedBy,
  });
}

