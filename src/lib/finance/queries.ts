async function unwrap<T>(promise: PromiseLike<{ data: T | null; error: { message: string } | null }>) {
  const { data, error } = await promise;
  if (error) throw new Error(error.message);
  return (data ?? []) as T;
}

export const financeKeys = {
  all: ["finance"] as const,
  entity: (name: string, params?: unknown) =>
    params === undefined ? (["finance", name] as const) : (["finance", name, params] as const),
};

export const walletsQuery = (ownerType?: Wallet["owner_type"]) =>
  queryOptions({
    queryKey: financeKeys.entity("wallets", ownerType ?? "all"),
    queryFn: () => {
      let q = supabase.from("finance_wallets").select("*").order("balance", { ascending: false });
      if (ownerType) q = q.eq("owner_type", ownerType);
      return unwrap<Wallet[]>(q);
    },
  });

export const walletTransactionsQuery = (entryType?: WalletTransaction["entry_type"]) =>
  queryOptions({
    queryKey: financeKeys.entity("wallet-transactions", entryType ?? "all"),
    queryFn: () => {
      let q = supabase
        .from("finance_wallet_transactions")
        .select("*, finance_wallets(owner_name, owner_code, owner_type)")
        .order("created_at", { ascending: false })
        .limit(200);
      if (entryType) q = q.eq("entry_type", entryType);
      return unwrap<(WalletTransaction & { finance_wallets: Pick<Wallet, "owner_name" | "owner_code" | "owner_type"> | null })[]>(q);
    },
  });

export const transactionsQuery = (filters?: {
  direction?: FinanceTransaction["direction"];
  status?: FinanceTransaction["status"];
  gateway?: string;
  limit?: number;
}) =>
  queryOptions({
    queryKey: financeKeys.entity("transactions", filters ?? {}),
    queryFn: () => {
      let q = supabase
        .from("finance_transactions")
        .select("*")
        .order("occurred_at", { ascending: false })
        .limit(filters?.limit ?? 150);
      if (filters?.direction) q = q.eq("direction", filters.direction);
      if (filters?.status) q = q.eq("status", filters.status);
      if (filters?.gateway) q = q.eq("gateway", filters.gateway);
      return unwrap<FinanceTransaction[]>(q);
    },
  });

